CREATE   PROCEDURE [dbo].[sp_interest_application_loan] --[SP_INTEREST_APPLICATION_LOAN] '2017-08-03',1 ,@successCount=null,@failureCount=null
@INTERESTRUNNINGDATE DATETIME,
@RUNBY NVARCHAR(20),
@successCount int OUTPut,
@failureCount int OUTPut

AS
BEGIN
declare @maxid bigint = 0
select @maxid = max(id) from BSGTURING.DBO.TURING_TASK_RESULT
	SELECT ROW_NUMBER() OVER (ORDER BY LAM.ID) SRNO,
		ABL.TXN_DATE,ABL.PENAL_INTEREST_ACCRUAL,ABL.INTEREST_ACCRUAL,LAM.BRANCH_CODE,LAM.CUSTOMER_NO,LAM.LOAN_ACCOUNT_ID,LAM.ASSET_CLASSIFICATION,LAM.LOAN_PRODUCT_ID  INTO #TEMP_ACCOUNT
	FROM 
		BSGLOAN.DBO.LOAN_ACCOUNT_MASTER LAM 
	
	left JOIN 
		(SELECT 
			LOAN_ACCOUNT_ID,
			MAX(TXN_DATE) TXN_DATE 
		FROM 
			BSGACCOUNTING.DBO.ACCOUNT_BALANCE_LOAN 
		WHERE 
			TXN_DATE <= @INTERESTRUNNINGDATE 
		AND 
			IS_ACTIVE=1 
		GROUP BY 
			LOAN_ACCOUNT_ID) TXN
	ON 
		LAM.LOAN_ACCOUNT_ID = TXN.LOAN_ACCOUNT_ID
	left JOIN 
		 BSGACCOUNTING.DBO.ACCOUNT_BALANCE_LOAN ABL
	ON 
		LAM.LOAN_ACCOUNT_ID = ABL.LOAN_ACCOUNT_ID
	AND 
		ABL.IS_ACTIVE =1
	AND 
		ABL.TXN_DATE =  TXN.TXN_DATE 
	WHERE 
		--LAM.ASSET_CLASSIFICATION IN (1,2) 
	--AND 
		LAM.loan_type=1 
	AND 
		LAM.IS_ACTIVE=1 
	AND 
		LAM.LOAN_ACCOUNT_STATUS=1
	--AND 
		--LAM.LOAN_ACCOUNT_ID in ( 741,1003)
		-- SELECT * FROM #TEMP_ACCOUNT

DECLARE @CBSAPPDATE DATETIME
DECLARE @ACCOUNT_ID BIGINT,@BRANCHCODE INT,@SCROLLNO BIGINT,
@BATCHCODE INT = (SELECT CONFIG_VALUE FROM BSGADMIN..CBS_CONFIG WHERE CONFIG_KEY = 'SYSTEM_AUTO_BATCH' AND IS_ACTIVE=1)
,@CNT NUMERIC(18,0) = (SELECT COUNT(1) FROM #TEMP_ACCOUNT)
,@TXNREFNO NVARCHAR(30),@TXN_TYPE INT = 2
,@PRODUCTID INT
,@PLACCOUNTID BIGINT
,@PLPRODUCTID BIGINT
,@PENALACCOUNTID BIGINT
,@PENALPRODUCTID BIGINT
,@PNLAMOUNT numeric(18,0)
,@INTERESTAMOUNT numeric(18,0)
,@assestClassification int

		SELECT @CBSAPPDATE = @INTERESTRUNNINGDATE --APP_DATE FROM BSGACCOUNTING..CBS_APPLICATION_DATE WHERE IS_ACTIVE=1

		--BEGIN TRANSACTION INTERESTAPPLIED WITH MARK N'INTEREST APPLIED';
		select @CNT 
		WHILE  @CNT > 0
		BEGIN
		print 'ACCOUNT_ID' + cast(@ACCOUNT_ID as nvarchar)
			SELECT @assestClassification = ASSET_CLASSIFICATION, @ACCOUNT_ID = LOAN_ACCOUNT_ID,
			@PRODUCTID = LOAN_PRODUCT_ID,			
			@BRANCHCODE=BRANCH_CODE,@PNLAMOUNT=PENAL_INTEREST_ACCRUAL,@INTERESTAMOUNT=INTEREST_ACCRUAL FROM #TEMP_ACCOUNT WHERE SRNO = @CNT
		
			SELECT @PENALACCOUNTID = PENAL_INTEREST_PL_ACCOUNT_ID,@PLACCOUNTID = INTEREST_INCOME_PL_CODE FROM  BSGLOAN.DBO.LOAN_PRODUCT_MASTER  WHERE LOAN_PRODUCT_ID = @PRODUCTID AND  IS_ACTIVE=1
		
		if( @assestClassification in (1,2))
		begin
			IF(@INTERESTAMOUNT <> 0)
			BEGIN
			SELECT @PLPRODUCTID = INTERNAL_PRODUCT_ID  FROM  BSGCORE.DBO.ACCOUNT_MASTER_INTERNAL  WHERE INTERNAL_ACCOUNT_ID = @PLACCOUNTID  AND IS_ACTIVE=1
				IF(@PLPRODUCTID IS NOT NULL)
				BEGIN
			-- GETTING MAX SCROLL NO
					SELECT @SCROLLNO = MAX(SCROLL_NO) FROM BSGACCOUNTING.DBO.TRANSACTION_SCROLLNO WHERE TXN_DATE=CAST(@CBSAPPDATE AS DATE) AND BRANCH_CODE = @BRANCHCODE AND BATCH_CODE = @BATCHCODE
					SET @SCROLLNO = ISNULL(@SCROLLNO+1,1) 
			-- CREATING NE REF NO 
					SET @TXNREFNO = CAST(@BRANCHCODE AS NVARCHAR)+ CAST(@BATCHCODE AS NVARCHAR)+ CAST(YEAR(GETDATE()) % 10 AS NVARCHAR)+ CAST(@SCROLLNO AS NVARCHAR) + '2'			
			-- INSERT NEW REF NO 
					INSERT INTO BSGACCOUNTING..TRANSACTION_SCROLLNO(TXN_DATE,BRANCH_CODE,BATCH_CODE,TXN_REF_NO,TXN_TYPE,SCROLL_NO,CREATED_BY,CREATED_DATE)
					VALUES(@CBSAPPDATE,@BRANCHCODE,@BATCHCODE,@TXNREFNO,@TXN_TYPE,@SCROLLNO,@RUNBY,GETDATE())
			-- VOUCHER ENTRY
			PRINT '@ACCOUNT_ID ' + CAST(@ACCOUNT_ID  AS NVARCHAR)+ '@PRODUCTID ' + CAST(@PRODUCTID AS NVARCHAR) + '@PLACCOUNTID '
			 + CAST(@PLACCOUNTID  AS NVARCHAR)
					+'@PLPRODUCTID'+CAST(@PLPRODUCTID AS NVARCHAR)+ '@TXNREFNO ' + CAST(@TXNREFNO AS NVARCHAR)+'@TXN_TYPE '+CAST(@TXN_TYPE AS NVARCHAR) 
					EXEC SP_VOUCHER_ENTRY @ACCOUNT_ID,@PRODUCTID,@PLACCOUNTID,@PLPRODUCTID,@TXNREFNO,1,@TXN_TYPE,@BATCHCODE,@SCROLLNO,@INTERESTAMOUNT,'D','000000',3004,'INTEREST APPLIED',@RUNBY,@CBSAPPDATE,0,3
				END
			END
			IF(@PNLAMOUNT <> 0)
			BEGIN
			SELECT @PENALPRODUCTID = INTERNAL_PRODUCT_ID  FROM  BSGCORE.DBO.ACCOUNT_MASTER_INTERNAL  WHERE INTERNAL_ACCOUNT_ID = @PENALACCOUNTID  AND IS_ACTIVE=1
			IF(@PENALPRODUCTID IS NOT NULL)
			BEGIN
			-- GETTING MAX SCROLL NO
					SELECT @SCROLLNO = MAX(SCROLL_NO) FROM BSGACCOUNTING.DBO.TRANSACTION_SCROLLNO WHERE TXN_DATE=CAST(@CBSAPPDATE AS DATE) AND BRANCH_CODE = @BRANCHCODE AND BATCH_CODE = @BATCHCODE
					SET @SCROLLNO = ISNULL(@SCROLLNO+1,1) 
			-- CREATING NE REF NO 
					SET @TXNREFNO = CAST(@BRANCHCODE AS NVARCHAR)+ CAST(@BATCHCODE AS NVARCHAR)+ CAST(YEAR(GETDATE()) % 10 AS NVARCHAR)+ CAST(@SCROLLNO AS NVARCHAR) + '2'			
			-- INSERT NEW REF NO 
					INSERT INTO BSGACCOUNTING..TRANSACTION_SCROLLNO(TXN_DATE,BRANCH_CODE,BATCH_CODE,TXN_REF_NO,TXN_TYPE,SCROLL_NO,CREATED_BY,CREATED_DATE)
					VALUES(@CBSAPPDATE,@BRANCHCODE,@BATCHCODE,@TXNREFNO,@TXN_TYPE,@SCROLLNO,@RUNBY,GETDATE())
			-- VOUCHER ENTRY
					EXEC SP_VOUCHER_ENTRY @ACCOUNT_ID,@PRODUCTID,@PLACCOUNTID,@PLPRODUCTID,@TXNREFNO,1,@TXN_TYPE,@BATCHCODE,@SCROLLNO,@PNLAMOUNT,'D','000000',3006,'PENAL APPLIED',@RUNBY,@CBSAPPDATE,1,3
			END
			END
			end
			else 
			begin
			IF(@INTERESTAMOUNT <> 0)
			BEGIN
			SELECT @PLPRODUCTID = INTERNAL_PRODUCT_ID  FROM  BSGCORE.DBO.ACCOUNT_MASTER_INTERNAL  WHERE INTERNAL_ACCOUNT_ID = @PLACCOUNTID  AND IS_ACTIVE=1
				IF(@PLPRODUCTID IS NOT NULL)
				BEGIN
			-- GETTING MAX SCROLL NO
					SELECT @SCROLLNO = MAX(SCROLL_NO) FROM BSGACCOUNTING.DBO.TRANSACTION_SCROLLNO WHERE TXN_DATE=CAST(@CBSAPPDATE AS DATE) AND BRANCH_CODE = @BRANCHCODE AND BATCH_CODE = @BATCHCODE
					SET @SCROLLNO = ISNULL(@SCROLLNO+1,1) 
			-- CREATING NE REF NO 
					SET @TXNREFNO = CAST(@BRANCHCODE AS NVARCHAR)+ CAST(@BATCHCODE AS NVARCHAR)+ CAST(YEAR(GETDATE()) % 10 AS NVARCHAR)+ CAST(@SCROLLNO AS NVARCHAR) + '2'			
			-- INSERT NEW REF NO 
					INSERT INTO BSGACCOUNTING..TRANSACTION_SCROLLNO(TXN_DATE,BRANCH_CODE,BATCH_CODE,TXN_REF_NO,TXN_TYPE,SCROLL_NO,CREATED_BY,CREATED_DATE)
					VALUES(@CBSAPPDATE,@BRANCHCODE,@BATCHCODE,@TXNREFNO,@TXN_TYPE,@SCROLLNO,@RUNBY,GETDATE())
			-- VOUCHER ENTRY
			PRINT '@ACCOUNT_ID ' + CAST(@ACCOUNT_ID  AS NVARCHAR)+ '@PRODUCTID ' + CAST(@PRODUCTID AS NVARCHAR) + '@PLACCOUNTID '
			 + CAST(@PLACCOUNTID  AS NVARCHAR)
					+'@PLPRODUCTID'+CAST(@PLPRODUCTID AS NVARCHAR)+ '@TXNREFNO ' + CAST(@TXNREFNO AS NVARCHAR)+'@TXN_TYPE '+CAST(@TXN_TYPE AS NVARCHAR) 
					EXEC [sp_loan_interest_application_npa] @ACCOUNT_ID,@PRODUCTID,@PLACCOUNTID,@PLPRODUCTID,@TXNREFNO,1,@TXN_TYPE,@BATCHCODE,@SCROLLNO,@INTERESTAMOUNT,'D','000000',3004,'NPA INTEREST APPLIED',@RUNBY,@CBSAPPDATE,0,3
				END
			END
			IF(@PNLAMOUNT <> 0)
			BEGIN
			SELECT @PENALPRODUCTID = INTERNAL_PRODUCT_ID  FROM  BSGCORE.DBO.ACCOUNT_MASTER_INTERNAL  WHERE INTERNAL_ACCOUNT_ID = @PENALACCOUNTID  AND IS_ACTIVE=1
			IF(@PENALPRODUCTID IS NOT NULL)
			BEGIN
			-- GETTING MAX SCROLL NO
					SELECT @SCROLLNO = MAX(SCROLL_NO) FROM BSGACCOUNTING.DBO.TRANSACTION_SCROLLNO WHERE TXN_DATE=CAST(@CBSAPPDATE AS DATE) AND BRANCH_CODE = @BRANCHCODE AND BATCH_CODE = @BATCHCODE
					SET @SCROLLNO = ISNULL(@SCROLLNO+1,1) 
			-- CREATING NE REF NO 
					SET @TXNREFNO = CAST(@BRANCHCODE AS NVARCHAR)+ CAST(@BATCHCODE AS NVARCHAR)+ CAST(YEAR(GETDATE()) % 10 AS NVARCHAR)+ CAST(@SCROLLNO AS NVARCHAR) + '2'			
			-- INSERT NEW REF NO 
					INSERT INTO BSGACCOUNTING..TRANSACTION_SCROLLNO(TXN_DATE,BRANCH_CODE,BATCH_CODE,TXN_REF_NO,TXN_TYPE,SCROLL_NO,CREATED_BY,CREATED_DATE)
					VALUES(@CBSAPPDATE,@BRANCHCODE,@BATCHCODE,@TXNREFNO,@TXN_TYPE,@SCROLLNO,@RUNBY,GETDATE())
			-- VOUCHER ENTRY
					EXEC [sp_loan_interest_application_npa] @ACCOUNT_ID,@PRODUCTID,@PLACCOUNTID,@PLPRODUCTID,@TXNREFNO,1,@TXN_TYPE,@BATCHCODE,@SCROLLNO,@PNLAMOUNT,'D','000000',3006,'NPA INTEREST APPLIED',@RUNBY,@CBSAPPDATE,1,3
			END
			END
			end
			SET @CNT -= 1
		END
		--COMMIT TRANSACTION  M2

		select @successCount = count(case when response_code = 1 then 1 else null end), 
		@failureCount =  count(case when response_code <> 1 then 1 else null end)
		  from   BSGTURING.DBO.TURING_TASK_RESULT where task_id=37 and id > @maxid
		 
END

